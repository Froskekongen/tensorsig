"""Exact quotient-native compilation in a partially commutative trace algebra.

This module is intentionally independent of the ambient Hall compiler.  It
constructs the graded Lie algebra generated by the retained letters inside the
partially commutative associative algebra, using exact sparse row reduction.
The resulting tensors are directly consumable by :class:`~SparseBCH`.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
import heapq
from typing import TypeAlias

import torch
from torch import Tensor

from .rules import (
    ChannelMultiplicity,
    ChannelSupport,
    DependenceGraph,
    LieQuotient,
    OffsetAlphabet,
    OffsetMultiplicity,
    OffsetSpan,
    OffsetSupport,
    ProjectedAlphabet,
    QuotientAlphabet,
    TemporalDegree,
)


__all__ = [
    "TraceBasisElement",
    "TraceLieQuotientPlan",
    "compile_trace_lie_quotient",
]


TraceWord: TypeAlias = tuple[int, ...]
_Polynomial: TypeAlias = dict[TraceWord, Fraction]


@dataclass(frozen=True)
class TraceBasisElement:
    """One deterministic quotient basis vector in exact trace coordinates.

    Parameters
    ----------
    depth : int
        Homogeneous Lie degree.
    multidegree : tuple[int, ...]
        Occurrence count of every zero-based alphabet letter.
    pivot : tuple[int, ...]
        Trace word used as the normalized echelon pivot.
    terms : tuple[tuple[tuple[int, ...], Fraction], ...]
        Sparse expansion in canonical trace words.
    """

    depth: int
    multidegree: tuple[int, ...]
    pivot: TraceWord
    terms: tuple[tuple[TraceWord, Fraction], ...]


@dataclass(frozen=True)
class TraceLieQuotientPlan:
    """Quotient-native basis and sparse bracket data compiled without Hall space.

    All tensors are CPU tensors.  ``generator_map`` has shape
    ``(alphabet.width, dimension)`` and ``bracket_indices`` is COO data with
    rows ``(left, right, output)``.
    """

    quotient: LieQuotient
    alphabet: QuotientAlphabet
    max_depth: int
    dependence_edges: frozenset[tuple[int, int]]
    basis: tuple[TraceBasisElement, ...]
    generator_map: Tensor
    basis_depths: Tensor
    bracket_indices: Tensor
    bracket_values: Tensor
    bracket_coefficients: tuple[Fraction, ...]

    def __post_init__(self) -> None:
        dimension = len(self.basis)
        if self.generator_map.shape != (self.alphabet.width, dimension):
            raise ValueError("generator_map has an invalid shape.")
        if self.basis_depths.shape != (dimension,):
            raise ValueError("basis_depths has an invalid shape.")
        if self.bracket_indices.ndim != 2 or self.bracket_indices.shape[1] != 3:
            raise ValueError("bracket_indices must have shape (nnz, 3).")
        if self.bracket_values.shape != (len(self.bracket_indices),):
            raise ValueError("bracket_values must have shape (nnz,).")
        if len(self.bracket_coefficients) != len(self.bracket_indices):
            raise ValueError("bracket_coefficients must have length nnz.")

    @property
    def dimension(self) -> int:
        """Dimension of the compiled quotient Lie algebra."""
        return len(self.basis)

    @property
    def level_dimensions(self) -> tuple[int, ...]:
        """Quotient dimensions in homogeneous levels ``1..max_depth``."""
        return tuple(
            sum(element.depth == depth for element in self.basis)
            for depth in range(1, self.max_depth + 1)
        )


@dataclass(frozen=True)
class _Reducer:
    index: int
    pivot: TraceWord
    polynomial: tuple[tuple[TraceWord, Fraction], ...]


class _TraceMonoid:
    def __init__(
        self,
        alphabet: QuotientAlphabet,
        dependence_edges: frozenset[tuple[int, int]],
    ) -> None:
        self._alphabet = alphabet
        self._dependence_edges = dependence_edges
        self._cache: dict[TraceWord, TraceWord] = {}

    def _channel(self, letter: int) -> int:
        if isinstance(self._alphabet, ProjectedAlphabet):
            return letter // self._alphabet.code_dim
        return letter % self._alphabet.in_channels

    def _dependent(self, left: int, right: int) -> bool:
        left_channel = self._channel(left)
        right_channel = self._channel(right)
        if left_channel == right_channel:
            return True
        edge = (min(left_channel, right_channel), max(left_channel, right_channel))
        return edge in self._dependence_edges

    def normal_form(self, word: TraceWord) -> TraceWord:
        """Return the lexicographically least word in one trace class."""
        cached = self._cache.get(word)
        if cached is not None:
            return cached

        followers: list[list[int]] = [[] for _ in word]
        indegree = [0] * len(word)
        for left in range(len(word)):
            for right in range(left + 1, len(word)):
                if self._dependent(word[left], word[right]):
                    followers[left].append(right)
                    indegree[right] += 1

        available = [
            (letter, position)
            for position, (letter, degree) in enumerate(zip(word, indegree))
            if degree == 0
        ]
        heapq.heapify(available)
        result = []
        while available:
            letter, position = heapq.heappop(available)
            result.append(letter)
            for follower in followers[position]:
                indegree[follower] -= 1
                if indegree[follower] == 0:
                    heapq.heappush(available, (word[follower], follower))

        normal = tuple(result)
        self._cache[word] = normal
        return normal


def _polynomial(terms: tuple[tuple[TraceWord, Fraction], ...]) -> _Polynomial:
    return dict(terms)


def _add_scaled(
    target: _Polynomial,
    source: _Polynomial,
    scale: Fraction,
) -> None:
    for word, coefficient in source.items():
        value = target.get(word, Fraction()) + scale * coefficient
        if value:
            target[word] = value
        else:
            target.pop(word, None)


def _multiply(
    left: _Polynomial,
    right: _Polynomial,
    monoid: _TraceMonoid,
) -> _Polynomial:
    result: _Polynomial = {}
    for left_word, left_coefficient in left.items():
        for right_word, right_coefficient in right.items():
            word = monoid.normal_form(left_word + right_word)
            result[word] = (
                result.get(word, Fraction()) + left_coefficient * right_coefficient
            )
    return {word: coefficient for word, coefficient in result.items() if coefficient}


def _bracket(
    left: _Polynomial,
    right: _Polynomial,
    monoid: _TraceMonoid,
) -> _Polynomial:
    result = _multiply(left, right, monoid)
    _add_scaled(result, _multiply(right, left, monoid), Fraction(-1))
    return result


def _reduce(
    polynomial: _Polynomial,
    reducers: list[_Reducer],
) -> tuple[_Polynomial, dict[int, Fraction]]:
    residual = dict(polynomial)
    coordinates: dict[int, Fraction] = {}
    for reducer in reducers:
        coefficient = residual.get(reducer.pivot, Fraction())
        if not coefficient:
            continue
        coordinates[reducer.index] = coefficient
        _add_scaled(residual, _polynomial(reducer.polynomial), -coefficient)
    return residual, coordinates


def _letter_channel(letter: int, alphabet: QuotientAlphabet) -> int:
    if isinstance(alphabet, ProjectedAlphabet):
        return letter // alphabet.code_dim
    return letter % alphabet.in_channels


def _retained(
    multidegree: tuple[int, ...],
    quotient: LieQuotient,
    alphabet: QuotientAlphabet,
) -> bool:
    channel_counts = [0] * alphabet.in_channels
    offset_counts = (
        [0] * alphabet.kernel_size if isinstance(alphabet, OffsetAlphabet) else []
    )
    temporal_degree = 0
    for letter, count in enumerate(multidegree):
        if not count:
            continue
        channel_counts[_letter_channel(letter, alphabet)] += count
        if isinstance(alphabet, ProjectedAlphabet):
            if alphabet.temporal_degrees is not None:
                temporal_degree += (
                    count * alphabet.temporal_degrees[letter % alphabet.code_dim]
                )
        else:
            offset_counts[letter // alphabet.in_channels] += count

    for rule in quotient.rules:
        if isinstance(rule, TemporalDegree):
            if temporal_degree > rule.maximum:
                return False
        elif isinstance(rule, ChannelMultiplicity):
            caps = (
                (rule.maximum,) * alphabet.in_channels
                if isinstance(rule.maximum, int)
                else rule.maximum
            )
            if any(count > cap for count, cap in zip(channel_counts, caps)):
                return False
        elif isinstance(rule, ChannelSupport):
            if sum(count > 0 for count in channel_counts) > rule.maximum:
                return False
        elif isinstance(rule, OffsetMultiplicity):
            if offset_counts and max(offset_counts) > rule.maximum:
                return False
        elif isinstance(rule, OffsetSupport):
            if sum(count > 0 for count in offset_counts) > rule.maximum:
                return False
        elif isinstance(rule, OffsetSpan):
            support = [offset for offset, count in enumerate(offset_counts) if count]
            if support and support[-1] - support[0] > rule.maximum:
                return False
    return True


def _validate(
    quotient: LieQuotient,
    alphabet: QuotientAlphabet,
    max_depth: int,
) -> frozenset[tuple[int, int]]:
    if not isinstance(quotient, LieQuotient):
        raise TypeError("quotient must be a LieQuotient.")
    if not isinstance(alphabet, (ProjectedAlphabet, OffsetAlphabet)):
        raise TypeError("alphabet must be ProjectedAlphabet or OffsetAlphabet.")
    if not isinstance(max_depth, int):
        raise TypeError("max_depth must be an integer.")
    if max_depth < 1:
        raise ValueError("max_depth must be positive.")

    graphs = [rule for rule in quotient.rules if isinstance(rule, DependenceGraph)]
    if not graphs:
        raise ValueError("trace compilation currently requires a DependenceGraph.")
    for graph in graphs:
        if any(right >= alphabet.in_channels for _, right in graph.edges):
            raise ValueError("DependenceGraph contains an out-of-range channel.")
    edges = set(graphs[0].edges)
    for graph in graphs[1:]:
        edges.intersection_update(graph.edges)

    for rule in quotient.rules:
        if isinstance(rule, TemporalDegree):
            if not isinstance(alphabet, ProjectedAlphabet):
                raise ValueError("TemporalDegree requires a ProjectedAlphabet.")
            if alphabet.temporal_degrees is None:
                raise ValueError("TemporalDegree requires explicitly graded letters.")
        if isinstance(
            rule, (OffsetMultiplicity, OffsetSupport, OffsetSpan)
        ) and not isinstance(alphabet, OffsetAlphabet):
            raise ValueError(f"{type(rule).__name__} requires an OffsetAlphabet.")
        if isinstance(rule, ChannelMultiplicity) and not isinstance(rule.maximum, int):
            if len(rule.maximum) != alphabet.in_channels:
                raise ValueError(
                    "ChannelMultiplicity requires one cap per alphabet channel."
                )
    return frozenset(edges)


def _add_multidegrees(
    left: tuple[int, ...],
    right: tuple[int, ...],
) -> tuple[int, ...]:
    return tuple(first + second for first, second in zip(left, right))


def compile_trace_lie_quotient(
    quotient: LieQuotient,
    alphabet: QuotientAlphabet,
    max_depth: int,
) -> TraceLieQuotientPlan:
    """Compile a graph quotient directly in exact trace-monoid coordinates.

    The construction is degree-generic.  It does not enumerate an ambient Hall
    basis, construct projection matrices, use dense linear algebra, or apply a
    numerical rank tolerance.

    Parameters
    ----------
    quotient : LieQuotient
        A dependence-graph quotient, optionally conjoined with supported
        upper-set rules.
    alphabet : ProjectedAlphabet or OffsetAlphabet
        Ordered generator alphabet and its channel/offset metadata.
    max_depth : int
        Largest homogeneous Lie degree to compile.

    Returns
    -------
    TraceLieQuotientPlan
        Exact basis metadata and float64 runtime tensors.
    """
    dependence_edges = _validate(quotient, alphabet, max_depth)
    monoid = _TraceMonoid(alphabet, dependence_edges)
    elements: list[TraceBasisElement] = []
    polynomials: list[_Polynomial] = []
    reducers_by_depth: dict[int, list[_Reducer]] = {
        depth: [] for depth in range(1, max_depth + 1)
    }

    def add_basis_element(
        polynomial: _Polynomial,
        multidegree: tuple[int, ...],
        depth: int,
    ) -> None:
        residual, _ = _reduce(polynomial, reducers_by_depth[depth])
        if not residual:
            return
        pivot = min(residual)
        pivot_coefficient = residual[pivot]
        normalized = {
            word: coefficient / pivot_coefficient
            for word, coefficient in residual.items()
        }
        terms = tuple(sorted(normalized.items()))
        index = len(elements)
        elements.append(
            TraceBasisElement(
                depth=depth,
                multidegree=multidegree,
                pivot=pivot,
                terms=terms,
            )
        )
        polynomials.append(normalized)
        reducers_by_depth[depth].append(
            _Reducer(index=index, pivot=pivot, polynomial=terms)
        )

    width = alphabet.width
    for letter in range(width):
        multidegree = tuple(int(position == letter) for position in range(width))
        if _retained(multidegree, quotient, alphabet):
            add_basis_element({(letter,): Fraction(1)}, multidegree, 1)

    for depth in range(2, max_depth + 1):
        previous_dimension = len(elements)
        for left in range(previous_dimension):
            for right in range(left + 1, previous_dimension):
                if elements[left].depth + elements[right].depth != depth:
                    continue
                multidegree = _add_multidegrees(
                    elements[left].multidegree,
                    elements[right].multidegree,
                )
                if not _retained(multidegree, quotient, alphabet):
                    continue
                add_basis_element(
                    _bracket(polynomials[left], polynomials[right], monoid),
                    multidegree,
                    depth,
                )

    generator_map = torch.zeros(width, len(elements), dtype=torch.float64)
    for letter in range(width):
        multidegree = tuple(int(position == letter) for position in range(width))
        if not _retained(multidegree, quotient, alphabet):
            continue
        residual, coordinates = _reduce({(letter,): Fraction(1)}, reducers_by_depth[1])
        if residual:  # pragma: no cover - degree-one generators are the basis
            raise RuntimeError("Could not reduce a retained quotient generator.")
        for index, coefficient in coordinates.items():
            generator_map[letter, index] = float(coefficient)

    constants: dict[tuple[int, int, int], Fraction] = {}
    for left in range(len(elements)):
        for right in range(left + 1, len(elements)):
            target_depth = elements[left].depth + elements[right].depth
            if target_depth > max_depth:
                continue
            multidegree = _add_multidegrees(
                elements[left].multidegree,
                elements[right].multidegree,
            )
            if not _retained(multidegree, quotient, alphabet):
                continue
            residual, coordinates = _reduce(
                _bracket(polynomials[left], polynomials[right], monoid),
                reducers_by_depth[target_depth],
            )
            if residual:  # pragma: no cover - basis construction spans brackets
                raise RuntimeError("Compiled quotient basis is not bracket closed.")
            for output, coefficient in coordinates.items():
                if coefficient:
                    constants[left, right, output] = coefficient
                    constants[right, left, output] = -coefficient

    ordered_constants = sorted(constants.items())
    bracket_indices = torch.tensor(
        [indices for indices, _ in ordered_constants],
        dtype=torch.long,
    ).reshape(-1, 3)
    bracket_values = torch.tensor(
        [float(value) for _, value in ordered_constants],
        dtype=torch.float64,
    )
    basis = tuple(elements)
    return TraceLieQuotientPlan(
        quotient=quotient,
        alphabet=alphabet,
        max_depth=max_depth,
        dependence_edges=dependence_edges,
        basis=basis,
        generator_map=generator_map,
        basis_depths=torch.tensor(
            [element.depth for element in basis], dtype=torch.long
        ),
        bracket_indices=bracket_indices,
        bracket_values=bracket_values,
        bracket_coefficients=tuple(value for _, value in ordered_constants),
    )
